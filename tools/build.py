#!/usr/bin/env python3
"""Builds dist/ for publishing:
  dist/index.html    the studio page (src/index.html)
  dist/studio.js     the studio logic (src/studio.js)
  dist/convert.js    description -> spec converter (src/convert.js)
  dist/knowledge.js  rules, schema and examples the studio sends to Claude (knowledge/)
  dist-manual/       the manual version (no Claude): the same files plus manual.js
  dist/engine.js     the cell engine: the Zapp cell preview with its builder, as an HTML string the studio
                     loads into a hidden frame, plus the cell templates (engine/)
Run from the repo root: python3 tools/build.py
"""
import glob, json, os, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E = lambda *p: os.path.join(ROOT, 'engine', *p)
DIST = os.path.join(ROOT, 'dist')
os.makedirs(DIST, exist_ok=True)
esc = lambda o: json.dumps(o, separators=(',', ':')).replace('</', '<\\/')
strip = lambda f: open(f).read().replace('export function', 'function').replace('export const', 'const')

bases = {os.path.basename(f)[:-10]: json.load(open(f)) for f in sorted(glob.glob(E('bases', '*.base.json')))}
tokens = {c: {os.path.basename(f)[:-12]: json.load(open(f)) for f in sorted(glob.glob(E('tokens', c, '*.tokens.json')))}
          for c in sorted(os.listdir(E('tokens')))}
actions = {'manifest': json.load(open(E('actions', 'actions.json'))),
           'icons': {os.path.basename(f)[:-5]: json.load(open(f)) for f in glob.glob(E('actions', 'icons', '*.json'))}}
icons = {os.path.basename(f)[:-5]: json.load(open(f)) for f in glob.glob(E('icons', '*.json'))}

# the engine page boots with one placeholder cell; the studio drives it through window.CellEngine
presets = [{'name': 'Engine', 'json': bases['cell_2_text'], 'pad': 0}]
t = open(E('template.html')).read()
for k, v in {'__PRESETS__': esc(presets), '__TOKENS__': esc(tokens), '__CELLS__': '[]', '__ACTIONS__': esc(actions),
             '__FEEDS__': '{}', '__LAYOUTS__': '{}', '__ICONS__': esc(icons),
             '__TOKENLIB__': strip(E('lib', 'tokens.mjs')), '__NEUTRALLIB__': strip(E('lib', 'scales.mjs'))}.items():
    assert k in t, k
    t = t.replace(k, v)
# engine mode: the studio owns Claude, downloads and storage; the engine page never asks for them
# (the template is written for the artifact skeleton, so it gets the same skeleton and reset here)
t = ('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
     '<script>window.CELL_ENGINE_MODE = 1;</script><style>body{margin:0;font:14px system-ui,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>'
     '</head><body>' + t + '</body></html>')
open(os.path.join(DIST, 'engine.js'), 'w').write(
    '// Generated by tools/build.py: do not edit.\nwindow.ENGINE_HTML = ' + json.dumps(t).replace('</', '<\\/') + ';\nwindow.CELL_BASES = ' + esc(bases) + ';\n')

K = lambda f: open(os.path.join(ROOT, 'knowledge', f)).read()
knowledge = {'version': K('rules.md').split('\n')[2].strip(), 'rules': K('rules.md'), 'schema': K('schema.md'), 'examples': json.loads(K('examples.json')),
             'icons': json.loads(K('icons.json')), 'decisions': json.loads(K('decisions.json'))['decisions']}
open(os.path.join(DIST, 'knowledge.js'), 'w').write('// Generated by tools/build.py from knowledge/: do not edit.\nwindow.KNOWLEDGE = ' + esc(knowledge) + ';\n')

for f in ('index.html', 'studio.js', 'convert.js'):
    shutil.copy(os.path.join(ROOT, 'src', f), os.path.join(DIST, f))

# the manual version (no Claude): the same studio plus src/manual.js, published as its own artifact from dist-manual/
MAN = os.path.join(ROOT, 'dist-manual')
os.makedirs(MAN, exist_ok=True)
for f in ('studio.js', 'convert.js', 'knowledge.js', 'engine.js'):
    shutil.copy(os.path.join(DIST, f), os.path.join(MAN, f))
shutil.copy(os.path.join(ROOT, 'src', 'manual.js'), os.path.join(MAN, 'manual.js'))
page = open(os.path.join(ROOT, 'src', 'index.html')).read()
for a, b in {'<title>Zapp Cell Style Studio</title>': '<title>Cell Style Studio Manual</title>',
             '<script src="studio.js"></script>': '<script src="manual.js"></script>\n<script src="studio.js"></script>'}.items():
    assert a in page, a
    page = page.replace(a, b)
open(os.path.join(MAN, 'index.html'), 'w').write(page)

for d in (DIST, MAN):
    print(os.path.basename(d) + '/')
    for f in sorted(os.listdir(d)):
        print(f'  {f:16} {os.path.getsize(os.path.join(d, f)) // 1024:6} KB')
